/**
 * sim-core/lib/gate.js — the authoritative mesh-quality gate.
 *
 * Writes a complete `meshQualityDict`, builds a read-only overlay next to the case,
 * runs `checkMesh -meshQuality`, and derives the verdict from the TEXT (checkMesh
 * exits 0 even when it prints `Failed N mesh checks`).
 *
 * Design rules:
 *  - the overlay lives in `<case>/.mesh-gate/<target>` — never in the project cache;
 *  - `minVol` is absolute, so when it is not configured for this mesh it is written
 *    as -1 (OpenFOAM disables the check) and the result says so, instead of failing
 *    a healthy mesh against an unrelated volume threshold;
 *  - `gate.engine: "script"` is an escape hatch for local QA scripts
 *    (`tools/qa/mesh_gate.sh`), but the JS engine stays authoritative by default.
 * @module sim-core/lib/gate
 */
import {
  cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, symlinkSync, writeFileSync,
} from 'node:fs'
import { join, resolve, sep } from 'node:path'
import { failKindOf, parseCheckMesh, verdictOf } from './checkmesh.js'
import { BUILTIN_GATE_PROFILES } from './project.js'
import { q, runBash } from './process.js'
import { tail } from './util.js'

/** All keys OpenFOAM's meshQualityDict understands (a missing key is a silent default). */
export const DICT_KEYS = [
  'maxNonOrtho', 'maxBoundarySkewness', 'maxInternalSkewness', 'maxConcave',
  'minVol', 'minTetQuality', 'minArea', 'minTwist', 'minDeterminant',
  'minFaceWeight', 'minVolRatio', 'minTriangleTwist', 'minEdgeLength',
]

/** Extra dict defaults that are not quality thresholds but must be present. */
const DICT_FIXED = {
  maxConcave: 80, minArea: -1, minTwist: 0.02, minTriangleTwist: -1, minEdgeLength: -1,
}

/** Merge built-in profile, project profiles and per-call overrides. */
export function resolveThresholds(profileName, profiles = {}, overrides = {}) {
  const builtin = BUILTIN_GATE_PROFILES[profileName] ?? BUILTIN_GATE_PROFILES.gate
  const project = profiles?.[profileName] ?? {}
  const merged = { ...builtin, ...project, ...(overrides ?? {}) }
  return { name: profileName in BUILTIN_GATE_PROFILES ? profileName : profileName, ...merged }
}

/** Render a complete meshQualityDict body. */
export function meshQualityDict(thresholds, minVol, minTetQuality) {
  const values = {
    ...DICT_FIXED,
    ...thresholds,
    minVol,
    minTetQuality,
  }
  const lines = [
    '/*--------------------------------*- C++ -*----------------------------------*\\',
    '  Generated by sim-core for this gate run; do not edit by hand.',
    '\\*---------------------------------------------------------------------------*/',
    'FoamFile',
    '{',
    '    version     2.0;',
    '    format      ascii;',
    '    class       dictionary;',
    '    object      meshQualityDict;',
    '}',
    '// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //',
    '',
  ]
  for (const key of DICT_KEYS) {
    const value = values[key]
    if (value === undefined || value === null) continue
    lines.push(`${key} ${typeof value === 'number' ? formatNumber(value) : value};`)
  }
  lines.push('nSmoothScale 4;', 'errorReduction 0.75;', '')
  return lines.join('\n')
}

function formatNumber(value) {
  if (!Number.isFinite(value)) return String(value)
  if (Number.isInteger(value)) return String(value)
  return String(Number(value.toPrecision(6)))
}

/** Region directories: `constant/<region>/polyMesh/boundary` next to the base mesh. */
export function detectRegions(caseDir) {
  const constantDir = join(caseDir, 'constant')
  if (!existsSync(constantDir)) return []
  return readdirSync(constantDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name !== 'polyMesh')
    .map((entry) => entry.name)
    .filter((name) => existsSync(join(constantDir, name, 'polyMesh', 'boundary')))
    .sort()
}

function safeName(name) {
  return String(name ?? 'base').replace(/[^A-Za-z0-9_.-]+/g, '_')
}

function linkOrCopy(target, path, isDir) {
  rmSync(path, { recursive: true, force: true })
  if (isDir) {
    try { symlinkSync(target, path, 'dir') } catch { cpSync(target, path, { recursive: true }) }
  } else {
    try { symlinkSync(target, path) } catch { cpSync(target, path) }
  }
}

/**
 * Build (or rebuild) the checkMesh overlay for a case or one of its regions.
 * Symlinks the mesh, copies `system`, links the matching `0` data.
 */
export function buildOverlay(caseDir, region = null) {
  const target = region ? `region-${safeName(region)}` : 'base'
  const root = join(caseDir, '.mesh-gate')
  const overlay = join(root, target)
  rmSync(overlay, { recursive: true, force: true })
  mkdirSync(join(overlay, 'constant'), { recursive: true })
  const systemSrc = join(caseDir, 'system')
  if (!existsSync(systemSrc)) throw new Error(`case has no system/ directory: ${caseDir}`)
  cpSync(systemSrc, join(overlay, 'system'), { recursive: true })
  const meshSrc = region ? join(caseDir, 'constant', region, 'polyMesh') : join(caseDir, 'constant', 'polyMesh')
  if (!existsSync(meshSrc)) throw new Error(`mesh not found: ${meshSrc}`)
  linkOrCopy(resolve(meshSrc), join(overlay, 'constant', 'polyMesh'), true)
  // 0/: whole directory for the base mesh, only `<region>/` for a region.
  const zeroSrc = join(caseDir, '0')
  if (existsSync(zeroSrc)) {
    if (region && existsSync(join(zeroSrc, region))) {
      mkdirSync(join(overlay, '0'), { recursive: true })
      linkOrCopy(resolve(join(zeroSrc, region)), join(overlay, '0', region), true)
    } else if (!region) {
      linkOrCopy(resolve(zeroSrc), join(overlay, '0'), true)
    }
  }
  return { overlay, target, meshSrc }
}

/** Run `checkMesh -meshQuality` inside the overlay and return raw text + exit code. */
export function runCheckMesh({ overlay, logPath, openfoamBashrc, timeoutMs, maxOutputChars, caseDir }) {
  mkdirSync(join(caseDir, 'logs'), { recursive: true })
  const result = runBash(`checkMesh -case ${q(overlay)} -meshQuality`, {
    cwd: caseDir,
    openfoamBashrc,
    timeoutMs,
    maxBuffer: 128 * 1024 * 1024,
  })
  const header = [
    `# checkMesh -meshQuality`,
    `# overlay: ${overlay}`,
    `# command: checkMesh -case ${q(overlay)} -meshQuality`,
    `# exit code: ${result.code}${result.timedOut ? ' (timed out)' : ''}`,
    '',
  ].join('\n')
  writeFileSync(logPath, `${header}${result.stdout}\n${result.stderr}\n`)
  return { ...result, log: logPath, text: `${result.stdout}\n${result.stderr}`, stderrTail: tail(result.stderr, maxOutputChars) }
}

/** Run an external gate script (`gate.engine: "script"`), e.g. `tools/qa/mesh_gate.sh`. */
export function runScriptGate({ script, caseDir, profile, minVol, timeoutMs, openfoamBashrc, maxOutputChars, rootDir }) {
  const resolved = resolve(rootDir, script)
  if (!existsSync(resolved)) {
    return { ok: false, error: `gate.script not found: ${script}`, candidates: [resolved] }
  }
  const jsonPath = join(caseDir, 'logs', `gate-script-${safeName(profile)}.json`)
  mkdirSync(join(caseDir, 'logs'), { recursive: true })
  const cmd = `bash ${q(resolved)} --case ${q(caseDir)} --profile ${q(profile)}`
    + (Number.isFinite(Number(minVol)) ? ` --min-vol ${Number(minVol)}` : '')
    + ` --json ${q(jsonPath)}`
  const run = runBash(cmd, { cwd: caseDir, openfoamBashrc, timeoutMs, maxBuffer: 64 * 1024 * 1024 })
  let report = null
  try { report = JSON.parse(readFileSync(jsonPath, 'utf8')) } catch { /* script did not write JSON */ }
  return { ok: true, script: resolved, command: cmd, exitCode: run.code, report, stdout: tail(run.stdout, maxOutputChars), stderr: tail(run.stderr, maxOutputChars) }
}

/**
 * Gate one target (case base mesh or one region).
 * @returns a report object with `verdict` PASS|FAIL|ERROR|UNKNOWN and `pass`.
 */
export function gateTarget(options) {
  const {
    config, caseDir: requestedCaseDir, region = null, profile = null, minVol = null, overrides = {},
    openfoamBashrc, timeoutMs, maxOutputChars, engine, script, logName = null,
  } = options
  // Always work with an absolute case path: `checkMesh` runs with cwd = caseDir,
  // so a relative path would be resolved twice (case/case/.mesh-gate).
  const caseDir = requestedCaseDir ? resolve(requestedCaseDir) : requestedCaseDir
  const profileName = String(profile ?? config?.gate?.profile ?? 'gate')
  const thresholds = resolveThresholds(profileName, config?.gate?.profiles ?? {}, overrides)
  const configuredMinVol = minVol ?? config?.gate?.minVol ?? null
  const effectiveMinVol = configuredMinVol === null || configuredMinVol === undefined || configuredMinVol === ''
    ? -1
    : Number(configuredMinVol)
  const minVolSource = configuredMinVol === null || configuredMinVol === undefined || configuredMinVol === ''
    ? 'disabled-minVol-not-configured'
    : (minVol !== null && minVol !== undefined ? 'call' : 'project-profile')
  const minTetQuality = effectiveMinVol > 0 ? Number((effectiveMinVol / 100).toPrecision(3)) : -1
  const bashrc = openfoamBashrc ?? config?.openfoamBashrc ?? ''
  if (!bashrc) {
    return {
      region, profile: profileName, verdict: 'ERROR', pass: false,
      error: 'OpenFOAM is not configured: no bashrc detected',
      hint: 'Source OpenFOAM and retry, or set <PREFIX>_OPENFOAM_BASHRC / sim-project.json foam.bashrc.',
    }
  }
  const useScript = (engine ?? config?.gate?.engine) === 'script' && Boolean(script ?? config?.gate?.script)
  if (useScript && (script ?? config?.gate?.script)) {
    const result = runScriptGate({
      script: script ?? config.gate.script, caseDir, profile: profileName,
      minVol: effectiveMinVol > 0 ? effectiveMinVol : null,
      timeoutMs, openfoamBashrc: bashrc, maxOutputChars, rootDir: config?.projectRoot || caseDir,
    })
    if (!result.ok) return { region, profile: profileName, verdict: 'ERROR', pass: false, ...result }
    const report = result.report ?? {}
    const verdict = String(report.verdict ?? 'UNKNOWN').toUpperCase()
    return {
      region, profile: profileName, engine: 'script', script: result.script, command: result.command,
      thresholds: report.thresholds ?? thresholds, minVol: report.minVol ?? effectiveMinVol,
      verdict, pass: verdict === 'PASS', metrics: report, report,
      stdout: result.stdout, stderr: result.stderr, exitCode: result.exitCode,
    }
  }

  const built = buildOverlay(caseDir, region)
  writeFileSync(join(built.overlay, 'system', 'meshQualityDict'), meshQualityDict(thresholds, effectiveMinVol, minTetQuality))
  const logPath = join(caseDir, 'logs', logName ?? `checkMesh-${built.target}.log`)
  const run = runCheckMesh({
    overlay: built.overlay, logPath, openfoamBashrc: bashrc,
    timeoutMs: timeoutMs ?? config?.timeoutMs, maxOutputChars, caseDir,
  })
  const metrics = parseCheckMesh(run.text)
  const verdict = verdictOf(metrics)
  let failKind = failKindOf(metrics, verdict)
  let suggestion = null
  if (failKind === 'minVol-threshold' && Number.isFinite(metrics.minVolume) && metrics.minVolume > 0) {
    suggestion = {
      minVol: Number((metrics.minVolume / 12).toPrecision(2)),
      reason: `smallest face-pyramid volume is ${metrics.minVolume}; minVol below it (≈ minVolume/12) stops flagging healthy cells`,
    }
  }
  const advisory = []
  if (minVolSource === 'disabled-minVol-not-configured') {
    advisory.push('minVol is not configured for this case, so the check is disabled (minVol -1). '
      + 'Set sim-project.json gate.minVol or pass minVol; the rule of thumb is h_min³/6.')
  }
  if (suggestion) advisory.push(`minVol ${effectiveMinVol} looks too strict: try ${suggestion.minVol}.`)
  if (verdict === 'UNKNOWN' && !metrics.meshOk && !metrics.failedChecks) {
    advisory.push('checkMesh printed neither "Mesh OK" nor a failure count — the log may be truncated; read the log file.')
  }
  return {
    region,
    profile: profileName,
    engine: 'js',
    thresholds: { ...thresholds, minVol: effectiveMinVol, minTetQuality },
    minVol: effectiveMinVol,
    minVolSource,
    minTetQuality,
    verdict,
    pass: verdict === 'PASS',
    metrics,
    failKind,
    suggestion,
    advisory,
    overlay: built.overlay,
    log: logPath,
    exitCode: run.code,
    timedOut: Boolean(run.timedOut),
    stdoutTail: tail(run.stdout, Math.min(maxOutputChars ?? 4000, 6000)),
    stderrTail: tail(run.stderr, 2000),
  }
}

/**
 * Gate a case: every region when region meshes exist, otherwise the base mesh.
 * @returns {{verdict: string, pass: boolean, targets: object[], regions: string[]}}
 */
export function gateCase(options) {
  const { caseDir } = options
  const regions = Array.isArray(options.regions) && options.regions.length
    ? options.regions
    : detectRegions(caseDir)
  const targets = regions.length ? regions : [null]
  const results = targets.map((region) => gateTarget({ ...options, region }))
  const verdicts = results.map((r) => r.verdict)
  const verdict = verdicts.includes('ERROR') ? 'ERROR'
    : verdicts.includes('FAIL') ? 'FAIL'
      : verdicts.every((v) => v === 'PASS') ? 'PASS' : 'UNKNOWN'
  return {
    caseDir,
    regions,
    targets: results,
    verdict,
    pass: verdict === 'PASS',
    failingRegions: results.filter((r) => r.verdict !== 'PASS').map((r) => r.region ?? 'base'),
  }
}

/** Human-readable one-liner for a gate result. */
export function gateSummary(result) {
  const parts = [`verdict=${result.verdict}`, `profile=${result.profile}`]
  if (result.metrics?.cells) parts.push(`cells=${result.metrics.cells}`)
  if (Number.isFinite(result.metrics?.maxNonOrtho)) parts.push(`maxNonOrtho=${result.metrics.maxNonOrtho}`)
  if (Number.isFinite(result.metrics?.maxSkewness)) parts.push(`maxSkew=${result.metrics.maxSkewness}`)
  if (Number.isFinite(result.metrics?.minVolume)) parts.push(`minVol=${result.metrics.minVolume}`)
  return parts.join('  ')
}

/** Exported for tests: the overlay root a case owns. */
export function overlayRoot(caseDir) {
  return join(caseDir, '.mesh-gate')
}

/** Guard used by tests: an overlay never leaves the case directory. */
export function isInsideCase(caseDir, path) {
  const root = resolve(caseDir) + sep
  return resolve(path).startsWith(root)
}
