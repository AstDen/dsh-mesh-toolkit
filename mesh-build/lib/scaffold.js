const FOAM_HEADER = (object) => `/*--------------------------------*- C++ -*----------------------------------*\\
  generated by the mesh-build plugin — review before a production run.
\\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      ${object};
}
`

function fmt(value) {
  const n = Number(value)
  if (!Number.isFinite(n)) throw new Error(`not a finite number: ${value}`)
  return Number.isInteger(n) ? String(n) : String(Number(n.toPrecision(10)))
}

function vec(p) {
  return `(${p.map(fmt).join(' ')})`
}

/**
 * Surface refinement level as {min, max}: a scalar applies to both bounds, a pair [min, max]
 * is written verbatim (`level (1 2)`), which is what the project's own cases use.
 * exp-003 needs [1, 2]; writing (2 2) gave 75 024 cells instead of 27 424 (DEF-12).
 */
export function normalizeLevel(value, fallback, name = '') {
  if (Array.isArray(value)) {
    const pair = value.map((v) => Math.max(0, Math.floor(Number(v))))
    if (pair.length !== 2 || !pair.every(Number.isFinite)) {
      throw new Error(`refinementLevels["${name}"] must be a level or a pair [min, max]; got ${JSON.stringify(value)}`)
    }
    return { min: Math.min(...pair), max: Math.max(...pair) }
  }
  const level = Math.max(0, Math.floor(Number(value ?? fallback)))
  if (!Number.isFinite(level)) throw new Error(`refinementLevels["${name}"] must be a number, got ${String(value)}`)
  return { min: level, max: level }
}

/** Normalise locationsInMesh input into [{ point, name }]. */
export function normalizeLocations(locations, defaultName = 'fluid') {
  // A single point is accepted in both documented forms, with or without the outer list:
  // [x,y,z] and { point: [x,y,z], name } are normalised to a one-element list.
  if (Array.isArray(locations) && locations.length === 3
      && locations.every((v) => (typeof v === 'number' && Number.isFinite(v)) || (typeof v === 'string' && v.trim() !== ''))) {
    locations = [locations]
  } else if (locations && !Array.isArray(locations) && Array.isArray(locations.point)) {
    locations = [locations]
  }
  if (!Array.isArray(locations) || locations.length === 0) {
    throw new Error('locationInMesh is required: [x,y,z] in meters, or [{ point:[x,y,z], name:"fluid" }, ...]')
  }
  return locations.map((entry, index) => {
    if (Array.isArray(entry)) {
      if (entry.length !== 3) throw new Error(`locationInMesh[${index}] must have 3 numbers`)
      return { point: entry.map(Number), name: index === 0 ? defaultName : `${defaultName}${index + 1}` }
    }
    if (entry && Array.isArray(entry.point)) {
      if (entry.point.length !== 3) throw new Error(`locationInMesh[${index}].point must have 3 numbers`)
      return { point: entry.point.map(Number), name: String(entry.name || (index === 0 ? defaultName : `${defaultName}${index + 1}`)) }
    }
    throw new Error(`locationInMesh[${index}] must be [x,y,z] or { point: [x,y,z], name }`)
  })
}

function inside(point, min, max) {
  return point.every((v, i) => v > min[i] && v < max[i])
}

