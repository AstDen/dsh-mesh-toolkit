/**
 * Write a runnable snappy case.
 * @returns {{caseDir: string, files: string[], warnings: string[], surfaces: object[], locations: object[]}}
 */
export function writeSnappyCase(config, caseDir, options) {
  // accept the expandStlInputs() result ({ files, missing }) as well as a plain path or a list of paths
  const rawStl = options.stl
  const stlInputs = Array.isArray(rawStl)
    ? rawStl
    : rawStl && Array.isArray(rawStl.files)
      ? rawStl.files
      : rawStl ? [rawStl] : []
  if (stlInputs.length === 0) throw new Error('scaffold needs stl: one or more STL paths (mm)')
  if (stlInputs.some((p) => typeof p !== 'string' || !p.trim())) {
    throw new Error('scaffold.stl must be STL paths (strings); got a non-path entry — pass { stl: ["<path>.stl"] }')
  }
  let domainMin = (options.domainMin ?? []).map(Number)
  let domainMax = (options.domainMax ?? []).map(Number)
  const domainNotes = []
  if (options.domain) {
    const spec = typeof options.domain === 'string' ? { type: options.domain } : options.domain
    const explicit = domainMin.length === 3 && domainMax.length === 3
    if (!explicit) {
      const bboxMm = readStlBboxMm(stlInputs[0])
      if (!bboxMm) throw new Error(`could not read the STL bounding box for domain sizing: ${stlInputs[0]}`)
      const computed = computeDomain({
        bboxMm,
        type: spec.type ?? 'external',
        margins: spec.margins,
        sizeFactor: spec.sizeFactor,
        flowAxis: spec.flowAxis,
      })
      domainMin = computed.domainMin
      domainMax = computed.domainMax
      domainNotes.push(...computed.notes)
    } else {
      domainNotes.push('explicit domainMin/domainMax override scaffoldOptions.domain — the domain mode was ignored')
    }
  }
  if (domainMin.length !== 3 || domainMax.length !== 3) throw new Error('domainMin and domainMax must be [x,y,z] in meters')
  if (!domainMin.every((v, i) => Number.isFinite(v) && v < domainMax[i])) throw new Error('domainMin must be strictly below domainMax on every axis')
  // D-8: no locationInMesh and a geometry to read -> pick the fluid point here, where the domain and
  // the STL surfaces are already resolved. `autoFluidPoint: false` keeps the explicit requirement.
  let autoPoint = null
  const hasLocation = (options.locationInMesh ?? options.locationsInMesh) != null
  if (!hasLocation && options.autoFluidPoint !== false && stlInputs.length > 0) {
    const auto = suggestFluidPoint(stlInputs, {
      domainMin,
      domainMax,
      clearance_mm: Number(options.autoFluidClearanceMm ?? 0.1),
      seed: Number(options.autoFluidSeed ?? 1),
      maxSeconds: Number(options.autoFluidMaxSeconds ?? 20),
    })
    if (auto.ok) {
      autoPoint = auto
      domainNotes.push(`locationInMesh not given: picked (${auto.point_mm.join(' ')}) mm, ${auto.clearance_mm} mm from the nearest wall (${auto.source})`)
    }
  }
  const locations = normalizeLocations(
    options.locationInMesh ?? options.locationsInMesh ?? (autoPoint ? autoPoint.point_m : undefined),
  )
  const cells = options.cells
    ? options.cells.map((v) => Math.max(1, Math.floor(Number(v))))
    : (() => {
        const size = options.cellSize != null
          ? Number(options.cellSize)
          : options.targetCells != null
            ? cellSizeFromTarget(domainMin, domainMax, options.targetCells)
            : NaN
        if (!Number.isFinite(size) || size <= 0) {
          throw new Error('scaffold needs cellSize (meters), targetCells or cells: [nx,ny,nz]')
        }
        if (options.targetCells != null && options.cellSize == null) {
          domainNotes.push(`targetCells ${Number(options.targetCells)} → background cell ${(size * 1e3).toFixed(4)} mm`)
        }
        return domainMin.map((v, i) => Math.max(1, Math.ceil((domainMax[i] - v) / size)))
      })()
  // The background cell that snappy will see: uniform when it comes from cellSize/targetCells,
  // the smallest axis spacing when the caller passed an explicit `cells` triple.
  const backgroundCellM = Math.min(...[0, 1, 2].map((i) => (domainMax[i] - domainMin[i]) / cells[i]))
  const warnings = [...domainNotes]
  for (const location of locations) {
    if (!inside(location.point, domainMin, domainMax)) {
      const hint = looksLikeMillimetres(location.point, domainMin, domainMax)
      throw new Error(
        `locationInMesh for "${location.name}" is outside the domain: ${vec(location.point)}`
        + ` (domain ${vec(domainMin)}…${vec(domainMax)} m)`
        + (hint ? ` — the point looks like millimetres: the case is in METRES, so divide by 1000 (${vec(hint)})` : ' — the point is in METRES')
        + '; mesh-build/scripts/fluid-point.py picks a fluid point from the STL',
      )
    }
  }

  if (cells.length !== 3 || !cells.every((n) => n > 0)) throw new Error('cells must be three positive integers')

  const levelDefaults = options.refinementLevels && typeof options.refinementLevels === 'object' ? options.refinementLevels : {}
  const defaultLevel = Math.max(0, Math.floor(Number(options.defaultLevel ?? 1)))
  const surfaces = stlInputs.map((raw) => {
    const file = resolveProjectPath(config, raw)
    if (!existsSync(file)) throw new Error(`STL not found: ${file}`)
    const name = stem(file)
    return { name, file, level: normalizeLevel(levelDefaults[name], defaultLevel, name) }
  })
  // A misspelled surface name used to fall back to defaultLevel without a word (DEF-13).
  const knownNames = new Set(surfaces.map((s) => s.name))
  const unknownKeys = Object.keys(levelDefaults).filter((key) => !knownNames.has(key))
  if (unknownKeys.length) {
    throw new Error(`refinementLevels key "${unknownKeys.join('", "')}" does not match any STL surface `
      + `(have: ${[...knownNames].join(', ') || 'none'}); the surface name is the STL file stem`)
  }
  // A clipped surface is the defect that produced a mesh with no inlet/outlet at all (exp-027
  // attempt 1: 438 787 illegal faces, gate still PASS). Refuse it; `allowClipping: true` is the
  // documented escape hatch for a deliberate cut.
  const clipped = []
  for (const surface of surfaces) {
    const outside = stlOutsideDomainWarning(surface.name, readStlBboxMm(surface.file), domainMin, domainMax)
    if (!outside) continue
    if (options.allowClipping === true) warnings.push(outside)
    else clipped.push(outside)
  }
  if (clipped.length) {
    throw new Error(`${clipped.join('; ')} — refusing to mesh: a clipped surface yields a mesh that passes `
      + 'checkMesh but has no inlet/outlet; enlarge the domain or pass scaffoldOptions.allowClipping: true '
      + 'if the cut is deliberate')
  }
  const budget = cellBudgetWarning(cells, Number(options.maxCells ?? 5_000_000))
  if (budget) warnings.push(budget)

  const patchType = options.symmetryDomain === false ? 'patch' : 'symmetry'
  const minVol = options.minVol != null ? Number(options.minVol) : 1e-14
  if (!Number.isFinite(minVol) || minVol <= 0) throw new Error('minVol must be a positive absolute volume (m^3)')
  // Thresholds for snappy's own quality loop: explicit option > gate profile > built-in default.
  const gateThresholds = options.gateThresholds ?? {}
  const maxNonOrtho = Number(options.maxNonOrtho ?? gateThresholds.maxNonOrtho ?? 65)
  const minVolRatio = Number(options.minVolRatio ?? gateThresholds.minVolRatio ?? 0.05)
  const minTwist = Number(options.minTwist ?? gateThresholds.minTwist ?? 0.02)

  const rawCellsBetween = options.nCellsBetweenLevels ?? 4
  const nCellsBetweenLevels = Number(rawCellsBetween)
  if (!Number.isInteger(nCellsBetweenLevels) || nCellsBetweenLevels < 1 || nCellsBetweenLevels > 10) {
    throw new Error(`nCellsBetweenLevels must be an integer 1..10 (got ${rawCellsBetween})`)
  }
  const refinementRegions = normalizeRefinementRegions(options.refinementRegions, domainMin, domainMax)
  const relaxedMaxNonOrtho = Number(options.relaxedMaxNonOrtho ?? Math.min(89, maxNonOrtho + 15))
  if (!Number.isFinite(relaxedMaxNonOrtho) || relaxedMaxNonOrtho <= 0 || relaxedMaxNonOrtho > 180) {
    throw new Error(`relaxedMaxNonOrtho must be a positive angle in degrees, at most 180 (got ${options.relaxedMaxNonOrtho})`)
  }

  const layerSurfaces = Array.isArray(options.layerSurfaces) ? options.layerSurfaces : []
  const nLayers = Math.max(1, Math.floor(Number(options.nLayers ?? 3)))
  const layers = layerSurfaces.map((surface) => {
    const name = String(surface)
    if (!surfaces.some((s) => s.name === name)) throw new Error(`layerSurfaces entry "${name}" does not match any STL surface (have: ${surfaces.map((s) => s.name).join(', ')})`)
    return {
      surface: name,
      nLayers,
      thickness: Number(options.layerThickness ?? 0.8),
      minThickness: Number(options.minThickness ?? 0.075),
      expansionRatio: Number(options.expansionRatio ?? 1.5),
    }
  })

  const np = Math.max(1, Math.floor(Number(options.np) || config.np || 1))
  const triSurface = join(caseDir, 'constant', 'triSurface')
  mkdirSync(triSurface, { recursive: true })
  for (const surface of surfaces) copyFileSync(surface.file, join(triSurface, `${surface.name}.stl`))

  const files = []
  const write = (relative, content) => {
    const full = join(caseDir, relative)
    writeFile(full, content)
    files.push(relative)
  }
  const caps = options.caps ?? (() => {
    const probed = probeCaps(config)
    // The capability matrix is what turns "asked for curvatureLevel on org14" into a refusal with a
    // reason instead of a dictionary the binary rejects at read time.
    return { ...probed, matrix: capabilityMatrix(probed, loadCapabilitiesMatrix(join(config.packageRoot, 'data'))) }
  })()
  write('system/blockMeshDict', blockMeshDict({ domainMin, domainMax, cells, patchType, unitsKey: caps.dictKeys?.blockMeshUnits ?? 'scale' }))
  const advanced = normalizeAdvanced(options.advanced ?? null)
  const support = advancedSupport(advanced, caps)
  if (support.unsupported.length) {
    throw new Error(
      `scaffoldOptions.advanced asks for keys this build does not accept: ${support.unsupported.map((u) => `${u.option} (needs ${u.needs})`).join(', ')}`
      + ` — this is ${caps.distribution} ${caps.version}; switch to com2606 (matrix: data/capabilities.json) or drop the option`,
    )
  }
  warnings.push(...support.warnings)
  for (const option of support.skipped) {
    const [group, field] = option.split('.')
    if (advanced?.[group]) advanced[group][field] = null
  }
  write('system/snappyHexMeshDict', snappyDict({
    surfaces, locations, defaultLevel, layers,
    resolveFeatureAngle: Number(options.resolveFeatureAngle ?? 30),
    layerAxisKey: caps.dictKeys?.layerAxis ?? 'minMedialAxisAngle',
    advanced,
    domainMin,
    domainMax,
    nCellsBetweenLevels,
    refinementRegions,
    relaxedMaxNonOrtho,
  }))
  write('system/meshQualityDict', meshQualityDict({ minVol, maxNonOrtho, minVolRatio, minTwist }))
  write('system/surfaceFeatureExtractDict', surfaceFeatureExtractDict(surfaces))
  write('system/surfaceFeaturesDict', surfaceFeaturesDict(surfaces))
  write('system/decomposeParDict', decomposeParDict(np))
  write('system/controlDict', controlDict())
  write('system/fvSchemes', fvSchemes())
  write('system/fvSolution', fvSolution())
  write('0/.keep', '')

  return {
    caseDir,
    caseDirDisplay: displayPath(config, caseDir),
    files,
    warnings,
    surfaces: surfaces.map((s) => ({
      name: s.name,
      stl: displayPath(config, s.file),
      level: s.level.min === s.level.max ? s.level.min : [s.level.min, s.level.max],
    })),
    locations,
    locationInMeshSource: autoPoint ? 'auto (lattice+nearest-triangle)' : 'given',
    fluidPoint: autoPoint,
    cells,
    cellSize_m: backgroundCellM,
    patchType,
    minVol,
    np,
    advanced,
    solverSkeleton:
      'simpleFoam, steady laminar (system/fvSchemes and system/fvSolution are usable as written; 0/U and 0/p are not written - take them from the workbench openfoam_case_scaffold or write your own)',
    units: { case: 'm', stl: 'mm (scale 0.001 in snappy geometry)' },
  }
}

/** Is this directory empty or missing? */
export function isEmptyDir(dir) {
  if (!existsSync(dir)) return true
  if (!statSync(dir).isDirectory()) return false
  return readdirSync(dir).length === 0
}

/** Copy extra STL files into constant/triSurface (used for existing cases). */
export function installStl(config, caseDir, stlInputs) {
  const dir = join(caseDir, 'constant', 'triSurface')
  mkdirSync(dir, { recursive: true })
  const copied = []
  for (const raw of stlInputs) {
    const file = resolveProjectPath(config, raw)
    if (!existsSync(file)) throw new Error(`STL not found: ${file}`)
    const target = join(dir, basename(file))
    copyFileSync(file, target)
    copied.push({ source: displayPath(config, file), target: displayPath(config, target) })
  }
  return copied
}

/**
 * A point well outside a small domain is usually a millimetre coordinate handed to a metre case:
 * the domain is < 0.5 m across and at least one component is >= 40x the domain extent (the classic
 * 10 mm cube with locationInMesh (4 4 4)).
 */
function looksLikeMillimetres(point, domainMin, domainMax) {
  const extent = domainMax.map((v, i) => v - domainMin[i])
  const maxExtent = Math.max(...extent)
  if (!(maxExtent > 0) || maxExtent > 0.5) return null
  const looksMm = point.some((v, i) => Math.abs(v) >= Math.max(20 * extent[i], 0.01))
  if (!looksMm) return null
  return point.map((v) => Number((v / 1000).toFixed(12)))
}
